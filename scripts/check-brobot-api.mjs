#!/usr/bin/env node
/**
 * Read-only freshness check for the generated brobot API models
 * (src/app/core/generated/). No Java, no network, no git, no writes:
 *
 *   node scripts/check-brobot-api.mjs
 *
 * The models are generated (scripts/generate-brobot-api.mjs) from brobot's
 * registered OpenAPI document: its entry in the superproject's contract
 * registry, libs/contracts/documents.yaml, at the commit that entry records.
 * Generation writes generated/.provenance.json, and this check fails when:
 *   - the registry's brobot entry names another repository, path or commit
 *     than the one the models were generated from (brobot moved its entry:
 *     regenerate);
 *   - a generation input changed: this app's openapitools.json (the jar pin)
 *     or the generation script (the generator's options);
 *   - a generated file was edited, removed or added by hand.
 * A commit names its content, so the document itself need not be re-read:
 * the same ref is the same document, and its sha256 is recorded for the
 * reader. The same shape as contracts' generated/.provenance.json check
 * (check-library-freshness.mjs --generated-only).
 */
import { createHash } from 'node:crypto';
import console from 'node:console';
import { existsSync, lstatSync, readdirSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

export const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** The superproject, which holds the contract registry. */
export const ROOT = resolve(APP, '../..');
export const FORMAT = 'brobot-api-models/v1';
export const DOCUMENT_NAME = 'brobot';
export const REGISTRY = 'libs/contracts/documents.yaml';
/** Relative to the app. */
export const GENERATED = 'src/app/core/generated';
export const PROVENANCE = `${GENERATED}/.provenance.json`;
/** Relative to the app: what generation reads besides the document. */
export const INPUTS = Object.freeze(['openapitools.json', 'scripts/generate-brobot-api.mjs']);
export const RECOVERY = 'pnpm --filter @singularity/brobot-admin-ui run generate:api';

/** sha256 of a text file, line endings normalised so a CRLF checkout hashes the same. */
export function hashText(bytes) {
    return createHash('sha256').update(bytes.toString('utf8').replace(/\r\n/g, '\n')).digest('hex');
}

/** The registry's brobot entry, `{ repository, ref, path }`. Throws when it is missing or in-repo. */
export function registryEntry(root = ROOT) {
    // The superproject's own yaml (a root devDependency), as contracts' checks use.
    const { parse } = createRequire(import.meta.url)('yaml');
    const registry = parse(readFileSync(join(root, REGISTRY), 'utf8'));
    const entry = registry?.documents?.find(document => document?.name === DOCUMENT_NAME);
    if (!entry) throw new Error(`${REGISTRY} has no "${DOCUMENT_NAME}" document`);
    const { repository, ref, path } = entry.location ?? {};
    if (typeof repository !== 'string' || typeof path !== 'string' || !/^[0-9a-f]{40}$/.test(String(ref))) {
        throw new Error(`${REGISTRY}: "${DOCUMENT_NAME}" is not a { repository, ref: <40-hex commit>, path } location`);
    }
    return { repository, ref, path };
}

/** Every file under the generated directory, relative to it, except the provenance itself. */
export function generatedFiles(app = APP) {
    const base = join(app, GENERATED);
    const walk = directory => readdirSync(join(base, directory), { withFileTypes: true }).flatMap(entry => {
        const path = directory ? `${directory}/${entry.name}` : entry.name;
        if (entry.isSymbolicLink()) throw new Error(`Symlink in ${GENERATED}: ${path}`);
        if (entry.isDirectory()) return walk(path);
        return entry.isFile() && path !== '.provenance.json' ? [path] : [];
    });
    return existsSync(base) ? walk('').sort() : [];
}

export function inputHashes(app = APP) {
    return Object.fromEntries(INPUTS.map(path => [path, hashText(readFileSync(join(app, path)))]));
}

/**
 * Diagnostics as `{ reason, path, message }`; empty when the models are fresh.
 * @param {{ app?: string, root?: string }} [options]
 */
export function checkBrobotApi({ app = APP, root = ROOT } = {}) {
    const diagnostics = [];
    const report = (reason, path, message) => diagnostics.push({ reason, path, message });
    const manifest = join(app, PROVENANCE);
    if (!existsSync(manifest) || !lstatSync(manifest).isFile()) {
        report('missing', PROVENANCE, 'no provenance: the models were not generated by scripts/generate-brobot-api.mjs');
        return diagnostics;
    }
    let provenance;
    try { provenance = JSON.parse(readFileSync(manifest, 'utf8')); }
    catch (error) { report('invalid', PROVENANCE, error.message); return diagnostics; }
    if (provenance?.format !== FORMAT) {
        report('invalid', PROVENANCE, `format is ${JSON.stringify(provenance?.format)}, expected ${FORMAT}`);
        return diagnostics;
    }

    let entry;
    try { entry = registryEntry(root); }
    catch (error) { report('invalid', REGISTRY, error.message); }
    if (entry) {
        for (const key of ['repository', 'ref', 'path']) {
            if (provenance.document?.[key] !== entry[key]) {
                report('stale', REGISTRY, `the registry's ${DOCUMENT_NAME} ${key} is ${entry[key]}; the models were generated from ${provenance.document?.[key]}`);
            }
        }
    }

    for (const [path, hash] of Object.entries(inputHashes(app))) {
        if (provenance.inputs?.[path] !== hash) report('stale', path, 'changed since the models were generated');
    }
    for (const path of Object.keys(provenance.inputs ?? {})) {
        if (!INPUTS.includes(path)) report('invalid', PROVENANCE, `records an input this check does not know: ${path}`);
    }

    const recorded = provenance.outputs ?? {};
    const present = generatedFiles(app);
    for (const path of present) {
        if (!(path in recorded)) report('unexpected', `${GENERATED}/${path}`, 'not written by generation');
        else if (recorded[path] !== hashText(readFileSync(join(app, GENERATED, path)))) report('edited', `${GENERATED}/${path}`, 'differs from what generation wrote');
    }
    for (const path of Object.keys(recorded)) {
        if (!present.includes(path)) report('missing', `${GENERATED}/${path}`, 'written by generation, now gone');
    }

    const version = join(app, GENERATED, '.openapi-generator/VERSION');
    if (existsSync(version) && readFileSync(version, 'utf8').trim() !== provenance.generator?.version) {
        report('invalid', `${GENERATED}/.openapi-generator/VERSION`, `does not match the recorded generator ${provenance.generator?.version}`);
    }
    return diagnostics;
}

export function formatDiagnostics(diagnostics) {
    return [...diagnostics.map(item => `${item.reason}: ${item.path}: ${item.message}`),
        `The brobot API models in ${GENERATED} are not what brobot's registered document generates. Regenerate them, never hand-edit (needs Java 17+):`,
        `  ${RECOVERY}`].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        const diagnostics = checkBrobotApi();
        if (diagnostics.length) { console.error(formatDiagnostics(diagnostics)); process.exitCode = 1; }
        else console.info('brobot API models match the registered document.');
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}
